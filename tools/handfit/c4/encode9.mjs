// studio/hand-contacts.js from the contact solves (cont/<gun>-<r|l>.json): each hold's give, packed (the vertex numbers as
// Uint16, the pushes as Int16 in 5 µm), base64
import fs from 'node:fs';
const dir = process.argv[2], out = process.argv[3];
const pack = (k) => { const n = k.idx.length, b = Buffer.alloc(n * 2 + n * 6); for (let i = 0; i < n; i++) b.writeUInt16LE(k.idx[i], i * 2); for (let i = 0; i < n * 3; i++) b.writeInt16LE(Math.max(-32767, Math.min(32767, Math.round(k.d[i] / 5e-6))), n * 2 + i * 2); return n + ':' + b.toString('base64'); };
const all = JSON.parse(JSON.stringify((await import('/home/claude/handfit-work/c4/hand-contacts.orig.js')).HAND_CONTACTS_RAW));   // CD-1: the hands not refitted keep theirs
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const [gun, sd] = f.replace('.json', '').split(/-(?=[rl]$)/), J = JSON.parse(fs.readFileSync(dir + '/' + f, 'utf8'));
  (all[gun] = all[gun] || {})[sd] = { pose: J.pose, glove: pack(J.glove), bare: pack(J.bare), pads: J.pads ? pack(J.pads) : '0:' };
}
let src = `// CL-334 h (Jerry, 10 Nov, J126 rule 2: "No part of the hand may clip through any part of a weapon"): where each gun's
// first-person hold presses the hand into a hard grip, the hand's surface gives (the glove's and the bare hand's): the
// vertices pushed out of the gun and the push smoothed over the skin round them, as flesh gives. Generated by the hand-fit
// tools in the cloud (docs/fps/hand.md: the gun's exported shape, its distance field, the solve); do not edit by hand.
// Each: the pose it was made for (the hold's VM_SOCKETS gripPose / supportPose), and per surface 'n:base64' of the vertex
// numbers (Uint16) then the pushes (Int16 x 3, 5 micrometres, the canonical right hand's space; the left mirrors).
export const HAND_CONTACTS_RAW = ${JSON.stringify(all, null, 0).replace(/\},"/g, '},\n  "')};
const CACHE = new Map();
function unpack(s) {
  const i = s.indexOf(':'), n = +s.slice(0, i), bin = atob(s.slice(i + 1)), u = new Uint8Array(bin.length);
  for (let k = 0; k < bin.length; k++) u[k] = bin.charCodeAt(k);
  const dv = new DataView(u.buffer), idx = new Uint16Array(n), d = new Float32Array(n * 3);
  for (let k = 0; k < n; k++) idx[k] = dv.getUint16(k * 2, true);
  for (let k = 0; k < n * 3; k++) d[k] = dv.getInt16(n * 2 + k * 2, true) * 5e-6;
  return { idx, d };
}
// The give for a gun's hold, decoded once: { pose, glove, bare, pads } for rig.setContact, or null.
export function handContact(key, side) {
  const id = key + '|' + side; if (CACHE.has(id)) return CACHE.get(id);
  const r = HAND_CONTACTS_RAW[key] && HAND_CONTACTS_RAW[key][side];
  const c = r ? { pose: r.pose, glove: unpack(r.glove), bare: unpack(r.bare), pads: unpack(r.pads || '0:') } : null;
  CACHE.set(id, c); return c;
}
`;
fs.writeFileSync(out, src);
console.log('wrote', out, (src.length / 1024).toFixed(0) + ' KB', Object.keys(all).join(' '));
