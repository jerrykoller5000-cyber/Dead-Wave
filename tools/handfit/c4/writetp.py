# writetp.py <fits.json> <out tp-fit.js>: TP_FIT (CD-9) from {gun: {r: {basis, p, pose}, l: {...}}}
import json, sys
F = json.load(open(sys.argv[1]))
r5 = lambda v: [round(float(x), 5) for x in v]
def pose(p): return {'f': [[round(float(v), 3) for v in q] for q in p['f']], 't': [round(float(v), 3) for v in p['t']]}
L = ['// GENERATED by tools/handfit (CD-9, Claude 1): the third-person fit of the one-handgun hold (J142d/e in third person).',
     '// Per gun and hand: p, the 3P wrist group\'s grip point (wrist.userData.grip, what holdHand puts on the anchor) in the gun\'s',
     '// space; basis.x / basis.y, the 3P wrist group\'s own +x and +y in the gun\'s space (z = x cross y: the whole hand frame on',
     '// the gun, its roll included); pose, the fingers (studio/marine-hand.js HAND_POSES keys). The hold (index.html, Claude 2)',
     '// puts the hand there: the wanted world turn is the gun\'s world quaternion times this frame, the forearm\'s roll takes',
     '// its share and the wrist the rest, inside core/body-limits.js ARM_LIMITS. One gun in his hands only (akimbo keeps its own).',
     'export const TP_FIT = {']
for g, H in F.items():
    L.append(f'  {g}: {{')
    for sd in ('r', 'l'):
        h = H[sd]; L.append(f'    {sd}: {json.dumps({"basis": {"x": r5(h["basis"]["x"]), "y": r5(h["basis"]["y"])}, "p": r5(h["p"]), "pose": pose(h["pose"])})},')
    L.append('  },')
L.append('};')
open(sys.argv[2], 'w').write('\n'.join(L) + '\n'); print('wrote', sys.argv[2])
