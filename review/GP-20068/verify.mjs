import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { serve } from '../../tools/serve.mjs';
import { launch } from '../../tools/cdp.mjs';

if (!process.env.DW_GAME_TEST_TOKEN) throw new Error('use the shared game-test slot');
const root = path.resolve(fileURLToPath(new URL('../..', import.meta.url)));
const server = await serve(root, 0);
const browser = await launch({ headless: false, args: ['--disable-features=CalculateNativeWinOcclusion', '--window-size=1280,720'] });
const results = [];
const ok = (name, value) => results.push({ name, pass: !!value });
try {
  const page = await browser.newPage({ width: 1280, height: 720 });
  await page.goto(`${server.origin}/index.html?debug=1`);
  if (!await page.waitFor('!!window.TT && window.DWLoad?.snapshot().state === "ready"', { timeout: 60000 })) throw new Error('game did not load');
  ok('title inspector can list gun prices before night one', await page.evaluate(`TT.armoryDbg.mods('m4').some(m => m.id === 'optic:acog' && m.price > 0)`));
  await page.evaluate('DWOpening.dismissForTesting()');
  if (!await page.waitFor('document.getElementById("opening").hidden', { timeout: 15000 })) throw new Error('opening did not dismiss');
  await page.evaluate(`(() => { document.querySelector('#playerName').value = 'Armory Tester'; document.querySelector('#modeHunt').click(); })()`);
  if (!await page.waitFor('TT.getPhase() === "prep" && !document.body.classList.contains("deploying")', { timeout: 60000 })) throw new Error('prep did not start');
  await page.evaluate(`window.gp68Receipts = []; addEventListener('dw-game', ({ detail }) => { if (detail.type === 'purchase-delivered') gp68Receipts.push(detail); }); TT.addCash(4000); TT.setDay(4); TT.openShop(true)`);
  ok('kiosk has supplies and builds only', await page.evaluate(`[...document.querySelectorAll('#shopTabs button')].map(x => x.textContent).join('|') === 'Supplies|Builds'`));
  ok('kiosk has field intel', await page.evaluate(`!!document.querySelector('#shopList [data-item="field-intel"]')`));
  ok('kiosk has no gun or laser/light row', await page.evaluate(`!document.querySelector('#shopList [data-weapon]') && !document.querySelector('#shopList .perk .name')?.textContent.includes('Laser/light')`));
  await page.screenshot(path.join(root, 'review/GP-20068/kiosk.png'));
  await page.evaluate(`document.querySelector('#shopTabs [data-shop-page="builds"]').click()`);
  ok('kiosk keeps structure plans', await page.evaluate(`document.querySelector('#shopList').textContent.includes('Wall blueprint')`));
  ok('kiosk omits weapon build plans', await page.evaluate(`!document.querySelector('#shopList').textContent.includes('Watchman MG blueprint')`));
  await page.evaluate(`TT.closeShop(); TT.openMenuDbg('armory')`);
  ok('Armory opens', await page.evaluate(`!document.querySelector('#armoryPanel').hidden`));
  await page.evaluate(`document.querySelector('#armoryPanel .armory-actions button:nth-child(2)').click()`);
  ok('Store opens from Armory', await page.evaluate(`document.querySelector('#shop').classList.contains('show') && document.querySelector('.shop-heading').textContent === 'Armory Store'`));
  ok('Armory lists gun, ammo and weapon builds', await page.evaluate(`[...document.querySelectorAll('#shopTabs button')].map(x => x.textContent).join('|') === 'Guns|Ammo|Weapon builds'`));
  await page.screenshot(path.join(root, 'review/GP-20068/store.png'));
  const beforeGun = await page.evaluate('TT.getBank()');
  await page.evaluate(`document.querySelector('#shopList [data-weapon="m4"] button').click()`);
  ok('gun bought for listed price', await page.evaluate(`TT.getWeaponOwned().m4 && TT.getBank() === ${beforeGun} - 180`));
  await page.evaluate(`document.querySelector('#shopList [data-weapon="shotgun"] button').click()`);
  ok('second gun bought in Armory', await page.evaluate(`TT.getWeaponOwned().shotgun`));
  await page.evaluate(`TT.setMagazinesDbg('m4', 30, []); TT.setShopTabDbg('ammo')`);
  const beforeAmmo = await page.evaluate('TT.getBank()');
  const ammoPrice = await page.evaluate(`Number(document.querySelector('#shopList [data-ammo="m4"] button').textContent.slice(1))`);
  await page.evaluate(`document.querySelector('#shopList [data-ammo="m4"] button').click()`);
  ok('ammo bought for listed price', await page.evaluate(`TT.spareMagCount('m4') === 1 && TT.getBank() === ${beforeAmmo} - ${ammoPrice}`));
  await page.evaluate(`TT.setShopTabDbg('upgrades')`);
  ok('laser/light in Armory upgrades', await page.evaluate(`document.querySelector('#shopList').textContent.includes('Laser/light')`));
  const beforeLaser = await page.evaluate('TT.getBank()');
  await page.evaluate(`(() => { const row = [...document.querySelectorAll('#shopList .perk')].find(r => r.querySelector('.name')?.textContent.includes('Laser/light')); row.querySelector('button').click(); })()`);
  ok('laser/light bought in Armory', await page.evaluate(`TT.getGearOwned().laserLight && TT.getBank() === ${beforeLaser} - 90`));
  await page.evaluate(`document.querySelector('#shopTabs [data-shop-page="builds"]').click()`);
  ok('weapon build plan in Armory', await page.evaluate(`document.querySelector('#shopList').textContent.includes('Watchman MG blueprint')`));
  const beforePlan = await page.evaluate('TT.getBank()');
  await page.evaluate(`(() => { const row = [...document.querySelectorAll('#shopList .perk')].find(r => r.querySelector('.name')?.textContent.includes('Watchman MG blueprint')); row.querySelector('button').click(); })()`);
  ok('weapon build plan bought for listed price', await page.evaluate(`TT.getBuildUnlocked().m240 && TT.getBank() === ${beforePlan} - 260`));
  await page.evaluate(`document.querySelector('#shopClose').click()`);
  ok('Store returns to Armory', await page.evaluate(`!document.querySelector('#armoryPanel').hidden && !document.querySelector('#shop').classList.contains('show')`));
  await page.evaluate(`TT.armoryDbg.ui().bench('m4')`);
  ok('gun workbench shows optic price', await page.evaluate(`document.querySelector('#armoryPanel [data-mod="optic:acog"] .armory-mod-state').textContent.includes('$')`));
  const beforeMod = await page.evaluate('TT.getBank()');
  await page.evaluate(`document.querySelector('#armoryPanel [data-mod="optic:acog"] button').click()`);
  ok('optic bought at gun', await page.evaluate(`TT.armoryDbg.mods('m4').find(m => m.id === 'optic:acog').owned && TT.getBank() < ${beforeMod}`));
  await page.evaluate(`document.querySelector('#armoryPanel [data-mod="optic:acog"] button').click()`);
  ok('optic fitted at gun', await page.evaluate(`TT.armoryDbg.mods('m4').find(m => m.id === 'optic:acog').fitted`));
  ok('purchases retain Armory receipts', await page.evaluate(`['weapon:m4','ammo:m4','gear:laserLight','blueprint:m240','optic:acog:m4'].every(id => gp68Receipts.some(r => r.itemId === id && r.source === 'armory'))`));
  await page.screenshot(path.join(root, 'review/GP-20068/bench.png'));
  if (page.errors.length) console.log('Browser errors:', page.errors.slice(0, 4));
  for (const r of results) console.log(`${r.pass ? 'PASS' : 'FAIL'} ${r.name}`);
  if (results.some(r => !r.pass) || page.errors.length) throw new Error(`${results.filter(r => !r.pass).length} checks failed, ${page.errors.length} browser errors`);
  console.log(`${results.length} passed, 0 failed`);
} finally {
  await browser.close();
  await server.close();
}
