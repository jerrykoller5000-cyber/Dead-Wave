import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { serve } from '../../tools/serve.mjs';
import { launch } from '../../tools/cdp.mjs';

if (!process.env.DW_GAME_TEST_TOKEN) throw Error('Use crew game-test slot');
const root = path.resolve(fileURLToPath(new URL('../..', import.meta.url)));
const out = path.join(root, 'review/GP-20101');
const server = await serve(root, 0);
const browser = await launch({ headless: false, args: ['--window-size=1280,720'] });
try {
  const page = await browser.newPage({ width: 1280, height: 720 });
  await page.goto(`${server.origin}/index.html?debug=1&raf=timer`);
  assert(await page.waitFor('!!window.TT && window.DWLoad?.snapshot().state==="ready"', { timeout: 90000 }));
  await page.evaluate('DWOpening.dismissForTesting()');
  assert(await page.waitFor('document.getElementById("opening").hidden', { timeout: 15000 }));
  await page.evaluate(`(()=>{document.getElementById('playerName').value='GP-20101-views';document.getElementById('modeTraining').click()})()`);
  assert(await page.waitFor('TT.trainingDbg.state().active', { timeout: 90000 }));
  assert(await page.waitFor('!document.getElementById("trainingBlackout")?.classList.contains("on")', { timeout: 20000 }));
  const setup = await page.evaluate(`(()=>{const T=TT,d=T.trainingDbg.state().dummy,p=d.model.group.position,tg=T.trainingDbg.tg();
    T.AudioSys.setMuted(true);T.grantAllWeapons();T.setWeapon(T.WEAPON_ORDER.indexOf('chainsaw'));
    T.setUnarmedDbg(false);T.setViewFirstDbg(false);T.setWorldTime(.5);
    T.player.position.set(p.x,tg.floorY,p.z-.75);T.setVelDbg(0,0);T.setOtsAimDbg(0,0);
    T.aimPointDbg(p.x,tg.floorY+1.3,p.z);T.setAimYawDbg(0);
    T.setShotView({x:p.x+2.4,y:tg.floorY+1.55,z:p.z-3.0,tx:p.x,ty:tg.floorY+1.0,tz:p.z,fov:40});
    for(let i=0;i<60;i++)T.stepFrame(.016);
    T.setMouseFireDbg(true);for(let i=0;i<35;i++)T.stepFrame(.016);T.setMouseFireDbg(false);
    for(let i=0;i<2;i++)T.stepFrame(.016);
    return {thirdHits:d.state().byKind.chainsaw,thirdBlade:{...T.sawDbg.blade()},first:T.sawDbg.first()};
  })()`);
  await page.screenshot(path.join(out, 'after-saw-third-person.png'));
  await page.evaluate(`(()=>{const T=TT,p=T.trainingDbg.state().dummy.model.group.position;
    T.setShotView({x:p.x+2.5,y:p.y+2.4,z:p.z-1.5,tx:p.x,ty:p.y+1.3,tz:p.z,fov:48});
    T.stepFrame(.016);
  })()`);
  await page.screenshot(path.join(out, 'after-saw-third-person-elevated.png'));
  await page.evaluate('TT.setShotView(null)');
  const first = await page.evaluate(`(()=>{const T=TT,d=T.trainingDbg.state().dummy,p=d.model.group.position,tg=T.trainingDbg.tg();
    T.setSawHeatDbg(0);T.setViewFirstDbg(true);T.player.position.set(p.x,tg.floorY,p.z-.75);T.setVelDbg(0,0);
    T.setOtsAimDbg(0,0);T.aimPointDbg(p.x,tg.floorY+1.3,p.z);T.setAimYawDbg(0);
    for(let i=0;i<10;i++)T.stepFrame(.016);
    T.setMouseFireDbg(true);for(let i=0;i<35;i++)T.stepFrame(.016);T.setMouseFireDbg(false);
    for(let i=0;i<2;i++)T.stepFrame(.016);
    return {totalHits:d.state().byKind.chainsaw,firstBlade:{...T.sawDbg.blade()},first:T.sawDbg.first()};
  })()`);
  await page.screenshot(path.join(out, 'after-saw-first-person.png'));
  const proof = { setup, first, errors: page.errors };
  fs.writeFileSync(path.join(out, 'attack-view.json'), JSON.stringify(proof,null,2)+'\n');
  assert(setup.thirdHits > 0 && !setup.first, 'third-person saw must mark dummy');
  assert(first.totalHits > setup.thirdHits && first.first, 'first-person saw must add marks');
  assert.deepEqual(page.errors, []);
  console.log(`PASS GP-20101 saw view proof: 3P ${setup.thirdHits}, 1P +${first.totalHits-setup.thirdHits}, 0 page errors`);
} finally { await browser.close(); await server.close(); }
