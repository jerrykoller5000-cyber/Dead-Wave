import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { serve } from '../../tools/serve.mjs';
import { launch } from '../../tools/cdp.mjs';
if (!process.env.DW_GAME_TEST_TOKEN) throw Error('Use crew game-test slot');
const root = path.resolve(fileURLToPath(new URL('../..', import.meta.url)));
const out = path.join(root, 'review/GP-20081');
const runner = fs.readFileSync(path.join(out, 'drills-page.js'), 'utf8');
const server = await serve(root, 0), browser = await launch({headless:false,args:['--window-size=1280,720']});
const report={};
try {
  const page=await browser.newPage({width:1280,height:720});
  await page.goto(`${server.origin}/index.html?debug=1&raf=timer`);
  assert(await page.waitFor('!!window.TT && window.DWLoad?.snapshot().state === "ready"',{timeout:90000}));
  await page.evaluate('DWOpening.dismissForTesting()');
  assert(await page.waitFor('document.getElementById("opening").hidden',{timeout:15000}));
  await page.evaluate(`(()=>{document.getElementById('playerName').value='GP-20081 Eye';document.getElementById('modeTraining').click()})()`);
  assert(await page.waitFor('TT.trainingDbg.state().active && TT.getPhase()==="prep"',{timeout:90000}));
  assert(await page.waitFor('!document.getElementById("trainingBlackout")?.classList.contains("on")',{timeout:30000}));
  report.eye=await page.evaluate(`(()=>{const T=TT,tg=T.trainingDbg.tg(),s=tg.stations.rangeConsole,f=s.front;T.player.position.set(f.x,tg.floorY,f.z);T.setShotView({x:f.x,y:tg.floorY+1.65,z:f.z,tx:s.x,ty:tg.floorY+1.4,tz:s.z,fov:65});return {action:T.trainingDbg.action(),hint:document.getElementById('trainingHud')?.innerText||''}})()`);
  await new Promise(r=>setTimeout(r,650));
  await page.screenshot(path.join(out,'console-eye.png'));
  await page.evaluate('TT.rangeDbg.open()');
  await page.screenshot(path.join(out,'console-menu-1280.png'));
  await page.setViewport(390,844);
  await page.screenshot(path.join(out,'console-menu-390.png'));
  report.layout=await page.evaluate(`(()=>{const root=document.querySelector('#rangeConsole'),panel=root.querySelector('.rd-panel'),r=panel.getBoundingClientRect();return {width:innerWidth,scrollWidth:document.documentElement.scrollWidth,panelX:r.x,panelRight:r.right,buttons:[...root.querySelectorAll('button')].filter(b=>b.getBoundingClientRect().width<24).length}})()`);
  await page.setViewport(1280,720);
  report.failed=await page.evaluate(`(async()=>{const T=TT,tg=T.trainingDbg.tg(),F=T.rangeDbg.feature(),d=(await import('/ui/range-drills.js')).RANGE_DRILLS.find(x=>x.id==='first-steps');F.start(d);for(let i=0;i<42;i++){tg.update(.25);F.tick(.25);if(i%8===7)await new Promise(requestAnimationFrame)}const active=F.read(),shown=tg.targets.filter(x=>x.solid?.rangeOwned&&x.state==='up').length,hud=document.querySelector('#rangeDrillHud')?.innerText||'';F.attack('pistol',{source:'throwable'});for(let i=0;i<8;i++){tg.update(.25);F.tick(.25);await new Promise(requestAnimationFrame)}F.open();const result=document.querySelector('#rangeConsole .rd-last-run')?.innerText||'';return {active:active.state,wave:active.wave,shown,hud,result,stored:localStorage.getItem('tt_range_drills_v1')}})()`);
  await page.screenshot(path.join(out,'console-void-1280.png'));
  await page.evaluate('TT.rangeDbg.exit(); window.GP20081={index:40}');
  report.passed=await page.evaluate(runner,300000);
  await page.evaluate('TT.rangeDbg.open()');
  await page.screenshot(path.join(out,'console-pass-1280.png'));
  await page.setViewport(390,844);
  await page.screenshot(path.join(out,'console-pass-390.png'));
  report.mobileResult=await page.evaluate(`(()=>{const r=document.querySelector('#rangeConsole .rd-last-run').getBoundingClientRect();return {width:innerWidth,scrollWidth:document.documentElement.scrollWidth,left:r.left,right:r.right,top:r.top}})()`);
  report.persisted=await page.evaluate(`(()=>{const s=localStorage.getItem('tt_range_drills_v1');return {bytes:s?.length||0,version:JSON.parse(s||'{}').version}})()`);
  report.errors=page.errors;
  assert.equal(report.eye.action,'rangeConsole');
  assert.equal(report.layout.scrollWidth,390);
  assert(report.layout.panelX>=0&&report.layout.panelRight<=390);
  assert.equal(report.failed.active,'ACTIVE');
  assert(report.failed.shown>0);
  assert.match(report.failed.result,/VOID|DISQUALIFIED|grenade/i);
  assert.equal(report.failed.stored,null);
  assert.equal(report.passed.result?.state,'COMPLETED');
  assert.equal(report.passed.result?.cleared,report.passed.expected);
  assert.equal(report.persisted.version,2);
  assert.equal(report.mobileResult.scrollWidth,390);
  assert(report.mobileResult.left>=0&&report.mobileResult.right<=390&&report.mobileResult.top<300);
  assert.deepEqual(report.errors,[]);
  console.log(`PASS GP-20081 eye: console ${report.eye.action}, active ${report.failed.shown} target(s), void no record, clean ${report.passed.result.cleared}/${report.passed.expected} record, 390 fit, no page errors`);
} finally {
  fs.writeFileSync(path.join(out,'console-eye.json'),JSON.stringify(report,null,2));
  await browser.close(); await server.close();
}
