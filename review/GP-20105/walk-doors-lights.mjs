import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { serve } from '../../tools/serve.mjs';
import { launch } from '../../tools/cdp.mjs';

if (!process.env.DW_GAME_TEST_TOKEN) throw Error('Run through crew game-test slot');
const root = path.resolve(fileURLToPath(new URL('../..', import.meta.url)));
const out = path.join(root, 'review/GP-20105');
fs.mkdirSync(out, { recursive: true });
const server = await serve(root, 0);
const browser = await launch({ headless: false, args: ['--window-size=1280,720'] });
const report = { at: new Date().toISOString(), steps: [], failedResources: [], errors: [] };
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
try {
  const page = await browser.newPage({ width:1280, height:720 });
  await page.send('Network.enable');
  page.conn.onEvent(msg => {
    if (msg.sessionId !== page.sessionId || msg.method !== 'Network.responseReceived') return;
    const r = msg.params.response;
    if (r.status >= 400) report.failedResources.push({ status:r.status, url:r.url });
  });
  await page.goto(`${server.origin}/index.html?debug=1`);
  assert(await page.waitFor('!!window.TT && window.DWLoad?.snapshot().state==="ready"',{timeout:90000}));
  await page.evaluate('DWOpening.dismissForTesting()');
  assert(await page.waitFor('document.getElementById("opening").hidden',{timeout:15000}));
  await page.evaluate(`(()=>{document.getElementById('playerName').value='GP-20105 doors';document.getElementById('modeTraining').click()})()`);
  assert(await page.waitFor('TT.trainingDbg.state().active',{timeout:90000}));
  assert(await page.waitFor('!document.getElementById("trainingBlackout")?.classList.contains("on")',{timeout:20000}));
  await pause(1200);
  await page.evaluate('TT.setViewFirstDbg(true)');
  await pause(1200);
  report.steps.push(await page.evaluate(`(()=>({name:'entry-first',fp:TT.fpDbg().first,blend:TT.fpDbg().w,camera:TT.camera.position.toArray(),gun:TT.getCurrentWeapon()}))()`));
  await page.screenshot(path.join(out,'20-entry-first-settled.png'));
  report.steps.push(await page.evaluate(`(()=>{const T=TT,tg=T.trainingDbg.tg(),f=tg.stations.lightSwitch.front;
    T.player.position.set(f.x,tg.floorY,f.z);T.setVelDbg(0,0);return {name:'light-switch',action:T.trainingDbg.action(),before:T.trainingDbg.lights()};})()`));
  await pause(300);
  await page.screenshot(path.join(out,'21-switch-lit-first.png'));
  report.steps.push(await page.evaluate(`(()=>{TT.doAction();return {name:'lights-off',lights:TT.trainingDbg.lights()};})()`));
  await pause(500);
  await page.screenshot(path.join(out,'22-switch-dark-first.png'));
  report.steps.push(await page.evaluate(`(()=>{TT.doAction();return {name:'lights-on',lights:TT.trainingDbg.lights()};})()`));
  await pause(300);
  const k = await page.evaluate(`(()=>{const T=TT,tg=T.trainingDbg.tg(),k=tg.securityDoor.keypads[0];
    T.player.position.set(k.front.x,tg.floorY,k.front.z);T.setVelDbg(0,0);
    return {front:k.front,action:T.trainingDbg.action(),before:T.trainingDbg.state().security.read(),doorY:tg.securityDoor.shutter.position.y};})()`);
  report.steps.push({name:'keypad-first',...k});
  await pause(300);
  await page.screenshot(path.join(out,'23-keypad-closed-first.png'));
  report.steps.push(await page.evaluate(`(()=>{const T=TT;T.doAction();return {name:'door-toggled',security:T.trainingDbg.state().security.read(),doorY:T.trainingDbg.tg().securityDoor.shutter.position.y};})()`));
  await pause(300);
  await page.screenshot(path.join(out,'24-keypad-open-first.png'));
  await page.evaluate('TT.setViewFirstDbg(false)');
  await pause(1100);
  report.steps.push(await page.evaluate(`(()=>({name:'keypad-third',fp:TT.fpDbg().first,camera:TT.camera.position.toArray(),doorY:TT.trainingDbg.tg().securityDoor.shutter.position.y}))()`));
  await page.screenshot(path.join(out,'25-keypad-open-third.png'));
  report.steps.push(await page.evaluate(`(()=>{TT.trainingDbg.leave();return {name:'exit',training:TT.trainingDbg.state().active,bodyClass:document.body.classList.contains('training')};})()`));
  await pause(300);
  await page.screenshot(path.join(out,'26-after-exit.png'));
  report.errors = page.errors.slice();
  assert.equal(report.steps.find(s=>s.name==='light-switch').action,'trainingLights');
  assert.equal(report.steps.find(s=>s.name==='lights-off').lights.on,false);
  assert.equal(report.steps.find(s=>s.name==='lights-on').lights.on,true);
  assert.equal(report.steps.find(s=>s.name==='keypad-first').action,'trainingDoor');
  assert.equal(report.steps.find(s=>s.name==='exit').training,false);
  assert.deepEqual(report.errors,[]);
  console.log(`GP-20105 doors/lights: first and third views, light off/on, keypad, exit; ${report.failedResources.length} failed resources, ${report.errors.length} page errors`);
} catch (e) { report.failure=String(e?.stack||e); console.error(report.failure); process.exitCode=1; }
finally { fs.writeFileSync(path.join(out,'walk-doors-lights.json'),JSON.stringify(report,null,2)+'\n'); await browser.close(); await server.close(); }
