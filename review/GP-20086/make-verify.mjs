import fs from 'node:fs';
const src='review/GP-20086/probe.mjs',dst='review/GP-20086/verify.mjs';
let s=fs.readFileSync(src,'utf8');
const anchor='  proof.layout=await page.evaluate';
if(!s.includes(anchor))throw Error('anchor changed');
s=s.replace(anchor,'  await page.evaluate("window.__gp86Box=mesh=>TT.trainingDbg.state().zombieCollision.bounds(mesh)");\n'+anchor);
const re=/new T\.THREE\.Box3\(\)\.setFromObject\((z|c)\.mesh\)/g;
const hits=(s.match(re)||[]).length;
if(hits!==5)throw Error(`expected 5 box calls, got ${hits}`);
s=s.replace(re,(_,v)=>`__gp86Box(${v}.mesh)`);
s=s.replaceAll("stage.startsWith('after')","stage!=='before'");
fs.writeFileSync(dst,s);
console.log(`created ${dst}`);
