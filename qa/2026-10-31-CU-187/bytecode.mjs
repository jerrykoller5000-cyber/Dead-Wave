// CU-187: bytecode size of every function in the game's scripts, from V8 itself (Node's, V8 13.6): each file is compiled as a module
// with --no-lazy (every function gets its bytecode at compile time) and --print-bytecode; the listing is read as it streams and only
// "function name, Bytecode length" is kept. V8's default --max-optimized-bytecode-size is 60 KB: a function over it stays in the
// interpreter. Output: bytecode-sizes.json { file: [{ name, len }...] } (largest 400 a file).
//   node qa/2026-10-31-CU-187/bytecode.mjs
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const dir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(dir, '../..');

if (process.argv[2] === '--child') {
  const vm = await import('node:vm');
  const file = process.argv[3];
  let code = fs.readFileSync(path.join(root, file), 'utf8');
  if (file.endsWith('.html')) {
    const m = [...code.matchAll(/<script type="module">([\s\S]*?)<\/script>/g)];
    code = m.map((x) => x[1]).join('\n;\n');
  }
  try { new vm.SourceTextModule(code, { identifier: file }); } catch (e) { console.error('COMPILE ERROR ' + file + ': ' + String(e.message).slice(0, 200)); process.exit(3); }
  process.exit(0);
}

// the files: index.html's inline module, every module the page loads, and three
const files = ['index.html'];
for (const d of ['core', 'game', 'combat', 'studio', 'world', 'ui']) {
  const stack = [d];
  while (stack.length) {
    const cur = stack.pop();
    for (const e of fs.readdirSync(path.join(root, cur), { withFileTypes: true })) {
      const p = path.join(cur, e.name).replace(/\\/g, '/');
      if (e.isDirectory()) { if (!/node_modules|test|inspector/i.test(e.name)) stack.push(p); }
      else if (/\.m?js$/.test(e.name) && !/\.test\.m?js$|\.min\.js$/.test(e.name)) files.push(p);
    }
  }
}
files.push('vendor/three/three.core.js', 'vendor/three/three.webgpu.js');
const only = process.argv[2] === '--only' ? process.argv.slice(3) : null;   // --only <files relative to the repo>: just those, into bytecode-only.json
if (only) { files.length = 0; files.push(...only); }
const result = {};
let done = 0;
for (const file of files) {
  const sizes = new Map();   // name -> max length
  await new Promise((resolve) => {
    const child = spawn(process.execPath, ['--experimental-vm-modules', '--no-warnings', '--no-lazy', '--print-bytecode', fileURLToPath(import.meta.url), '--child', file], { cwd: root, stdio: ['ignore', 'pipe', 'pipe'] });
    let buf = '', cur = null;
    child.stdout.on('data', (b) => {
      buf += b.toString('utf8');
      let i;
      while ((i = buf.indexOf('\n')) >= 0) {
        const line = buf.slice(0, i); buf = buf.slice(i + 1);
        const m = /^\[generated bytecode for function: (.*?) \(0x[0-9a-f]+ <SharedFunctionInfo/.exec(line);
        if (m) { cur = m[1] || '(anonymous)'; continue; }
        const l = /^Bytecode length: (\d+)/.exec(line);
        if (l && cur != null) { sizes.set(cur, Math.max(sizes.get(cur) || 0, +l[1])); cur = null; }
      }
    });
    child.stderr.on('data', (b) => { const s = b.toString('utf8'); if (/COMPILE ERROR/.test(s)) console.error(s.trim()); });
    child.on('exit', resolve);
  });
  const arr = [...sizes].map(([name, len]) => ({ name, len })).sort((a, b) => b.len - a.len);
  result[file] = { functions: sizes.size, top: arr.slice(0, 400) };
  done++;
  if (done % 20 === 0) console.log(`${done}/${files.length} files`);
}
fs.writeFileSync(path.join(dir, only ? 'bytecode-only.json' : 'bytecode-sizes.json'), JSON.stringify(result), 'utf8');
const all = [];
for (const [file, v] of Object.entries(result)) for (const f of v.top) all.push({ file, ...f });
all.sort((a, b) => b.len - a.len);
console.log(`${files.length} files, ${all.length} listed; the largest 25:`);
for (const f of all.slice(0, 25)) console.log(`${String(f.len).padStart(7)}  ${f.name}  (${f.file})`);
